-- #4182: オブジェクトストレージへ写して確かめたドライブのファイルの、ローカルの実体を
-- 消す (#4179 の (4))。Elythia 独自の列。TS は知らない列を無視する。
--
-- objectStorageLocalDeletedAt: 消す処理が、消す直前にもう一度確かめてから、ローカルの
-- 実体を消した日時。写し直したとき・行をリンクに倒すとき・戻す処理 (#4183 で足す予定)
-- で NULL に戻す。消す処理は日時を入れてから実体を消すので、日時があればローカルは
-- 消えているか、消しそびれて残っている。NULL でもローカルがあるとは限らない (消す前の
-- 世代の DB のバックアップへ戻したときなど)。戻す処理は、ローカルの実体の有無と md5 を
-- 確かめてから使う (本体の md5。サムネイルと webpublic は行に md5 が無い)。
-- 値の無い列の追加なので、表は書き直さない。
ALTER TABLE "drive_file" ADD COLUMN IF NOT EXISTS "objectStorageLocalDeletedAt" TIMESTAMP WITH TIME ZONE;
